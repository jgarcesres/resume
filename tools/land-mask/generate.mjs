// Regenerates app/src/components/homelab/topologyFlow/land.ts: a 0.5° land
// bitmask of the Americas between the two homelab sites, drawn as the dot
// matrix behind the live map.
//
// Source: Natural Earth 1:50m land (public domain) via the world-atlas package.
// Not part of the app build; run by hand when the window needs to change:
//
//   cd tools/land-mask && npm i --no-save world-atlas@2 topojson-client@3
//   node generate.mjs > ../../app/src/components/homelab/topologyFlow/land.ts
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-50m.json');

const LON0 = -124, LON1 = -34, LAT0 = -20, LAT1 = 52, STEP = 0.5;
const COLS = (LON1 - LON0) / STEP, ROWS = (LAT1 - LAT0) / STEP;

const rings = [];
for (const poly of feature(topo, topo.objects.land).features[0].geometry.coordinates) {
  let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
  for (const [x, y] of poly[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  if (x1 < LON0 || x0 > LON1 || y1 < LAT0 || y0 > LAT1) continue;
  rings.push({ poly, x0, x1, y0, y1 });
}

function inRing(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function isLand(x, y) {
  for (const r of rings) {
    if (x < r.x0 || x > r.x1 || y < r.y0 || y > r.y1) continue;
    if (!inRing(r.poly[0], x, y)) continue;
    if (!r.poly.slice(1).some(hole => inRing(hole, x, y))) return true;
  }
  return false;
}

// A cell is land when at least two of four interior samples are, which keeps
// thin features (Florida, Panama, Cuba) from breaking up.
const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    let hits = 0;
    for (const [dx, dy] of [[0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75]]) {
      if (isLand(LON0 + (c + dx) * STEP, LAT1 - (r + dy) * STEP)) hits++;
    }
    if (hits >= 2) { const i = r * COLS + c; bytes[i >> 3] |= 1 << (i & 7); }
  }
}

const b64 = Buffer.from(bytes).toString('base64').match(/.{1,100}/g).join("' +\n  '");
process.stdout.write(`// land.ts — GENERATED by tools/land-mask/generate.mjs. Do not edit by hand.
//
// A ${STEP}° land bitmask (Natural Earth 1:50m, public domain) covering
// lon ${LON0}..${LON1}, lat ${LAT0}..${LAT1}. Row 0 is the northern edge; bit i of the
// stream is cell (row = floor(i / LAND.cols), col = i % LAND.cols).

export const LAND = {
  lon0: ${LON0},
  lat1: ${LAT1},
  step: ${STEP},
  cols: ${COLS},
  rows: ${ROWS},
} as const;

const B64 =
  '${b64}';

let cells: Uint8Array | null = null;

/** The bitmask as bytes, decoded once. */
export function landBits(): Uint8Array {
  if (!cells) {
    const raw = atob(B64);
    cells = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i++) cells[i] = raw.charCodeAt(i);
  }
  return cells;
}

export function isLandCell(row: number, col: number): boolean {
  if (row < 0 || col < 0 || row >= LAND.rows || col >= LAND.cols) return false;
  const i = row * LAND.cols + col;
  return (landBits()[i >> 3] & (1 << (i & 7))) !== 0;
}
`);
